"""
CSV loader for experimental data.

Supported formats:
- icmp_v2: ICMP monitoring generated by test_n1_link_failure_v2.py
- onos_links: ONOS link monitoring generated by monitor_onos_links.py

The loader preserves original CSV values as strings.
It does not modify source files or calculate experimental metrics.
"""

import csv
from pathlib import Path


ICMP_V2_REQUIRED_COLUMNS = {
    "utc_timestamp",
    "monotonic_seconds",
    "phase",
    "event",
    "icmp_sequence",
    "raw_ping_output",
}

ONOS_LINKS_REQUIRED_COLUMNS = {
    "timestamp_utc",
    "monotonic_time",
    "poll_duration_ms",
    "total_directional_links",
    "api_status",
}


class CSVValidationError(Exception):
    """Raised when an experimental CSV is invalid or unsupported."""


def detect_csv_format(columns):
    """
    Detect the experimental CSV format from its column names.

    Returns:
        str: 'icmp_v2' or 'onos_links'
    """

    column_set = set(columns)

    if ICMP_V2_REQUIRED_COLUMNS.issubset(column_set):
        return "icmp_v2"

    if ONOS_LINKS_REQUIRED_COLUMNS.issubset(column_set):
        return "onos_links"

    raise CSVValidationError(
        "Unsupported CSV format. "
        f"Columns found: {columns}"
    )


def load_csv(file_path, expected_format=None):
    """
    Load and validate an experimental CSV file.

    Args:
        file_path: Path to the CSV file.
        expected_format: Optional expected format ('icmp_v2' or 'onos_links').

    Returns:
        dict: Dataset metadata and original rows.

    Raises:
        FileNotFoundError: If the file does not exist.
        CSVValidationError: If the file is empty, invalid or unsupported.
    """

    path = Path(file_path)

    if not path.is_file():
        raise FileNotFoundError(f"CSV file not found: {path}")

    if path.stat().st_size == 0:
        raise CSVValidationError(f"CSV file is empty: {path}")

    try:
        with path.open(
            mode="r",
            encoding="utf-8-sig",
            newline=""
        ) as csv_file:

            reader = csv.DictReader(csv_file)

            if not reader.fieldnames:
                raise CSVValidationError(
                    f"CSV header not found: {path}"
                )

            columns = [
                column.strip() if column else ""
                for column in reader.fieldnames
            ]

            if any(not column for column in columns):
                raise CSVValidationError(
                    f"CSV contains an empty column name: {path}"
                )

            if len(columns) != len(set(columns)):
                raise CSVValidationError(
                    f"CSV contains duplicate column names: {path}"
                )

            detected_format = detect_csv_format(columns)

            if (
                expected_format is not None
                and detected_format != expected_format
            ):
                raise CSVValidationError(
                    f"Expected format '{expected_format}', "
                    f"but detected '{detected_format}' in {path}"
                )

            rows = []

            for line_number, row in enumerate(reader, start=2):

                if None in row:
                    raise CSVValidationError(
                        f"Unexpected number of fields at line "
                        f"{line_number}: {path}"
                    )

                if any(value is None for value in row.values()):
                    raise CSVValidationError(
                        f"Missing field at line {line_number}: {path}"
                    )

                # Preserve original values; do not convert or modify them.
                rows.append(row)

    except UnicodeDecodeError as error:
        raise CSVValidationError(
            f"CSV encoding is not supported: {path}"
        ) from error

    except csv.Error as error:
        raise CSVValidationError(
            f"Error reading CSV: {path}: {error}"
        ) from error

    if not rows:
        raise CSVValidationError(
            f"CSV contains a header but no data rows: {path}"
        )

    return {
        "file_path": str(path),
        "format": detected_format,
        "columns": columns,
        "row_count": len(rows),
        "rows": rows,
    }